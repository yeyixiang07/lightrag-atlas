#!/usr/bin/env python3
"""Render Markdown tables for the report from analysis CSV/JSON outputs."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
OUT = ROOT / "report" / "tables.md"

ORDER = ["c0_closed", "c1_naive", "c2_full", "c3_low", "c4_high", "c5_origin",
         "c6_empty", "c7_shuffled", "c8_extractive", "c9_temporal", "c10_naive_temporal"]
SHORT = {"c0_closed": "C0 闭卷", "c1_naive": "C1 NaiveRAG", "c2_full": "C2 LightRAG-Full",
         "c3_low": "C3 仅低层", "c4_high": "C4 仅高层", "c5_origin": "C5 去原文",
         "c6_empty": "C6 抽空画像", "c7_shuffled": "C7 打乱结构",
         "c8_extractive": "C8 抽取式画像", "c9_temporal": "C9 时序图",
         "c10_naive_temporal": "C10 Naive+时序"}


def f(x, nd=2):
    if x is None or (isinstance(x, float) and (np.isnan(x) or np.isinf(x))):
        return "—"
    return f"{x:.{nd}f}"


def ci(mean, lo, hi, nd=2):
    if mean is None or (isinstance(mean, float) and np.isnan(mean)):
        return "—"
    return f"{mean:.{nd}f} [{lo:.{nd}f}, {hi:.{nd}f}]"


def md_table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |",
             "|" + "|".join(["---"] * len(headers)) + "|"]
    for r in rows:
        lines.append("| " + " | ".join(str(x) for x in r) + " |")
    return "\n".join(lines)


def main() -> None:
    out = []
    out.append("<!-- generated by src/make_tables.py -->\n")

    p = RESULTS / "table_main.csv"
    if p.exists():
        df = pd.read_csv(p)
        df["order"] = df["condition"].map({c: i for i, c in enumerate(ORDER)})
        df = df.sort_values("order")
        rows = []
        for _, r in df.iterrows():
            rows.append([SHORT.get(r["condition"], r["label"]), int(r["n"]),
                         ci(r["correct_norm"], r["correct_norm_lo"], r["correct_norm_hi"]),
                         f(r["strict_correct"]), f(r["lenient_correct"]), f(r["f1"]),
                         f(r["semantic_cos"]), f(r["citation_precision"]),
                         f(r["citation_recall"]), f(r["has_citation"]), f(r["refusal"]),
                         f(r["evidence_recall"]), f(r["context_tokens"], 0)])
        out.append("### 表 1 主结果（100 题；均值与 95% bootstrap CI）\n")
        out.append(md_table(["条件", "n", "正确率 [95% CI]", "严格", "宽松", "F1",
                             "语义余弦", "引用精确率", "引用召回", "引用率", "拒答率",
                             "证据召回", "上下文 token"], rows))
        out.append("\n")

    p = RESULTS / "table_by_type.csv"
    if p.exists():
        df = pd.read_csv(p)
        rows = []
        for c in ORDER:
            sub = df[df["condition"] == c]
            if sub.empty:
                continue
            vals = []
            for t in ["factual", "multihop", "thematic", "temporal"]:
                x = sub[sub["type"] == t]
                vals.append(ci(x.iloc[0]["correct_norm"], x.iloc[0]["correct_norm_lo"],
                               x.iloc[0]["correct_norm_hi"]) if not x.empty else "—")
            rows.append([SHORT[c]] + vals)
        out.append("### 表 2 按题型的正确率（95% CI）\n")
        out.append(md_table(["条件", "事实细节 (30)", "多跳 (25)", "主题 (25)", "时序 (20)"], rows))
        out.append("\n")

    p = RESULTS / "table_paired.csv"
    if p.exists():
        df = pd.read_csv(p)
        rows = []
        for _, r in df.iterrows():
            scope = r["scope"]
            if scope in ("all", "temporal"):
                scope = "全题" if scope == "all" else "时序题"
            rows.append([r["family"], f"{SHORT.get(r['a'], r['a'])} − {SHORT.get(r['b'], r['b'])}",
                         scope, f(r["diff"], 3), f"[{r['lo']:.3f}, {r['hi']:.3f}]" if not pd.isna(r["lo"]) else "—",
                         f(r["p"], 4), f(r["p_holm"], 4), int(r["n"])])
        out.append("### 表 3 配对差异与显著性（Holm 校正）\n")
        out.append(md_table(["假设族", "比较", "范围", "Δ 正确率", "95% CI", "p", "p (Holm)", "n"], rows))
        out.append("\n")

    p = RESULTS / "table_h3_temporal.csv"
    if p.exists():
        df = pd.read_csv(p)
        sub = df[df["type"] == "temporal"]
        rows = []
        for c in ORDER:
            r = sub[sub["condition"] == c]
            if r.empty:
                continue
            r = r.iloc[0]
            rows.append([SHORT[c], int(r["n"]), f(r["correct_norm"]), f(r["order_accuracy"]),
                         f(r["sequence_correct"]), f(r["duration_correct"])])
        out.append("### 表 4 时序题细分（20 题）\n")
        out.append(md_table(["条件", "n", "正确率", "pairwise 顺序", "全序正确", "时长正确"], rows))
        out.append("\n")

    p = RESULTS / "table_profile_audit.csv"
    if p.exists():
        df = pd.read_csv(p)
        rows = []
        for _, r in df.iterrows():
            rows.append(["LLM 画像" if r["mode"] == "llm" else "抽取式画像",
                         "实体" if r["kind"] == "entity" else "关系",
                         int(r["n"]), f(r["mean_support"]), f(r["sd"])])
        out.append("### 表 5 画像事实性审计（每类 30 条）\n")
        out.append(md_table(["画像类型", "图元素", "n", "支持率", "sd"], rows))
        out.append("\n")

    p = RESULTS / "table_judge_agreement.csv"
    if p.exists():
        df = pd.read_csv(p)
        rows = []
        for _, r in df.iterrows():
            rows.append([SHORT.get(r["condition"], r["label"]), int(r["n"]), f(r["agreement"]),
                         f(r["kappa_3"]), f(r["kappa_binary"]), f(r["spearman"])])
        out.append("### 表 6 双 judge 一致性（Qwen2.5-7B vs Llama-3.1-8B）\n")
        out.append(md_table(["条件", "n", "一致率", "κ (二次加权)", "κ (严格二分类)", "Spearman"], rows))
        out.append("\n")

    p = RESULTS / "cost_summary.json"
    if p.exists():
        cs = json.loads(p.read_text(encoding="utf-8"))
        q = pd.DataFrame(cs["query"])
        rows = []
        for c in ORDER:
            r = q[q["condition"] == c]
            if r.empty:
                continue
            r = r.iloc[0]
            rows.append([SHORT[c], int(r["n_uncached"]), int(r["llm_calls_per_query"]),
                         f(r["prompt_tokens"], 0), f(r["completion_tokens"], 0),
                         f(r["total_tokens"], 0), f(r["latency_p50"]), f(r["latency_p95"]),
                         f(r["context_tokens"], 0), f(r["graph_tokens"], 0),
                         f(r["chunk_tokens"], 0), f(r["timeline_tokens"], 0)])
        out.append("### 表 7 全周期成本与查询延迟\n")
        out.append(md_table(["条件", "n (未缓存)", "LLM 调用/query", "prompt token",
                             "completion token", "总 token", "P50 (s)", "P95 (s)",
                             "上下文 token", "图画像 token", "原文 token", "时间线 token"], rows))
        out.append("\n")
        out.append(f"索引：{cs['indexing']['llm_calls']} 次 LLM 调用，"
                   f"{cs['indexing']['prompt_tokens']:,} prompt tokens，"
                   f"{cs['indexing']['completion_tokens']:,} completion tokens，"
                   f"调用墙钟合计 {cs['indexing']['wall_seconds_sum_of_calls']:.1f} s"
                   f"（含首次加载的全量构建实测 {cs['indexing']['wall_seconds_full_build_measured']:.1f} s）。\n")
        inc = cs["incremental"]
        out.append(f"增量更新（前 14 chunk → 追加后 14 chunk）：全量重建 {inc['full_rebuild_tokens']:,} token，"
                   f"增量更新 {inc['incremental_update_tokens']:,} token，"
                   f"节省 {inc['token_saving_fraction']*100:.1f}%。\n")
        st = cs["storage_bytes"]
        out.append(f"存储：图 JSON {st.get('graph_c2.json',0)/1024:.0f} KB，"
                   f"时序图 {st.get('graph_c9.json',0)/1024:.0f} KB，"
                   f"C2 画像 {st.get('profiles_c2.json',0)/1024:.0f} KB，"
                   f"C8 画像 {st.get('profiles_c8.json',0)/1024:.0f} KB，"
                   f"embedding {st.get('embeddings_total',0)/1024/1024:.1f} MB。\n")

    p = RESULTS / "human_audit_summary.json"
    if p.exists():
        h = json.loads(p.read_text(encoding="utf-8"))
        out.append("### 表 8 人工盲审与 judge 的一致性\n")
        out.append(md_table(["n", "原始一致率", "κ (二次加权)", "κ (严格二分类)"],
                            [[h.get("n"), f(h.get("agreement")), f(h.get("kappa_3")), f(h.get("kappa_binary"))]]))
        out.append("\n")

    OUT.write_text("\n".join(out), encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
